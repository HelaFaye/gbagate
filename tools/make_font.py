FIRST, LAST = 32, 126

TAIL = r'''

const uint8_t *ui_font_glyph(char c) {
    unsigned char u = (unsigned char)c;
    if (u < UI_FONT_FIRST || u > UI_FONT_LAST) {
        u = ' ';
    }
    return ui_font5x7[u - UI_FONT_FIRST];
}

uint16_t ui_font_width(const char *s) {
    if (!s || !*s) {
        return 0;
    }
    uint16_t n = 0;
    while (*s++) {
        n++;
    }
    /* n glyphs, n-1 gaps: the trailing gap is not part of the ink. */
    return (uint16_t)(n * UI_FONT_ADVANCE - 1);
}

uint16_t ui_font_fit(const char *s, uint16_t max_px) {
    if (!s) {
        return 0;
    }
    uint16_t n = 0;
    uint16_t used = 0;
    while (s[n]) {
        uint16_t next = (uint16_t)(used ? used + UI_FONT_ADVANCE : UI_FONT_W);
        if (next > max_px) {
            break;
        }
        used = next;
        n++;
    }
    return n;
}'''
missing = [chr(c) for c in range(FIRST, LAST + 1) if chr(c) not in G]
if missing:
    raise SystemExit("missing glyphs: %r" % missing)

out = []
out.append('/*')
out.append(' * ui_font.c -- 5x7 bitmap font. GENERATED by tools/make_font.py; edit the')
out.append(' * glyphs there, not here.')
out.append(' *')
out.append(' * Column major, one byte per column, bit 0 = top row; rows 0-6 reach the')
out.append(' * baseline and row 7 holds descenders. 5 columns plus a 1px')
out.append(' * gap gives 21 characters across 128px, and the longest chip name in the')
out.append(' * tables is 11 characters, so names fit the 66px name column with room over.')
out.append(' */')
out.append('')
out.append('#include "ui_font.h"')
out.append('')
out.append('const uint8_t ui_font5x7[UI_FONT_GLYPHS][UI_FONT_W] = {')
for c in range(FIRST, LAST + 1):
    ch = chr(c)
    rows = G[ch]
    cols = []
    for x in range(5):
        b = 0
        for y in range(8):
            if rows[y][x] == '#':
                b |= 1 << y
        cols.append(b)
    label = ch if ch not in ('\\',) else '\\\\'
    out.append('    { 0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X },  /* %s */'
               % (*cols, "'%s'" % label if ch != ' ' else 'space'))
out.append('};')
out.append('')
# The measuring functions live in the generated file too, so regenerating it
# keeps them: the file used to carry them by hand, and this script, run
# as written, dropped them.
out.append(TAIL)
# src/ui_font.c, wherever this is run from.
import os
dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'ui_font.c')
open(dest, 'w').write('\n'.join(out) + '\n')
print('wrote %s with %d glyphs' % (os.path.normpath(dest), LAST - FIRST + 1))
