"""
make_font.py -- generate ui_font.c, a 5x7 bitmap font.

Glyphs are drawn here as text so they can be read and edited, then emitted as
column-major bytes (bit 0 = top row). An original design rather than a lifted
one, drawn to suit a 128px line: 5 wide plus a 1px gap gives 21 columns, and
the longest chip name in the tables is 11 characters.
"""

G = {}

def g(ch, *rows):
    # Seven rows down to the baseline, and an eighth below it for descenders:
    # g, j, p, q and y give all eight; everything else gives seven.
    assert len(rows) in (7, 8), (ch, len(rows))
    for r in rows:
        assert len(r) == 5, (ch, r)
    G[ch] = rows + ('.....',) * (8 - len(rows))

