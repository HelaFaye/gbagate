#!/usr/bin/env python3
"""mb_embed.py -- the memory agent's image as a C array, for the firmware.

    python3 tools/mb_embed.py rom/agent.mb src/gbagent_image.c
    python3 tools/mb_embed.py --check rom/agent.mb src/gbagent_image.c

The firmware build (ESP-IDF, in CI's container) has no ARM toolchain, so the
image is built from rom/ with one -- `make agent-image` -- and the bytes are
committed here. The generated file records a hash of the agent's sources;
--check (run by qemu/lint.sh) fails when those sources or the image have
moved on without the array, so an edited agent cannot ship stale.
"""
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = ['rom/agent.c', 'rom/agent_proto.h', 'rom/crt0_mb.s', 'rom/multiboot.ld']


def source_hash():
    h = hashlib.sha256()
    for p in SOURCES:
        h.update(p.encode() + b'\0')
        h.update(open(os.path.join(ROOT, p), 'rb').read())
    return h.hexdigest()[:16]


def render(image, src_hash, image_name):
    lines = [
        '/*',
        ' * gbagent_image.c -- rom/agent.mb, the memory agent, for Send Program to',
        ' * deliver. GENERATED by tools/mb_embed.py (make agent-image); do not edit.',
        ' *',
        ' * The logo area is blank: the board fills it from a program on its drive',
        ' * before sending (rom_borrow_logo), so none of Nintendo\'s bytes ship.',
        ' *',
        ' * sources: %s' % src_hash,
        ' * image:   %s, %d bytes' % (hashlib.sha256(image).hexdigest()[:16], len(image)),
        ' */',
        '#include "gbagent_image.h"',
        '',
        'const uint32_t gbagent_image_len = %d;' % len(image),
        'const uint8_t gbagent_image[%d] = {' % len(image),
    ]
    for i in range(0, len(image), 16):
        lines.append('    ' + ' '.join('0x%02x,' % b for b in image[i:i + 16]))
    lines.append('};')
    return '\n'.join(lines) + '\n'


def main(argv):
    check = argv[1:2] == ['--check']
    if check:
        argv = argv[1:]
    if len(argv) != 3:
        print(__doc__)
        return 2
    image = open(argv[1], 'rb').read()
    want = render(image, source_hash(), argv[1])
    if not check:
        open(argv[2], 'w').write(want)
        print('%s: %d bytes from %s' % (argv[2], len(image), argv[1]))
        return 0
    have = open(argv[2]).read() if os.path.exists(argv[2]) else ''
    m = re.search(r'sources: ([0-9a-f]+)', have)
    if not m or m.group(1) != source_hash():
        print('the agent\'s sources changed since %s was generated: run make agent-image' % argv[2])
        return 1
    if have != want:
        print('%s does not match %s: run make agent-image' % (argv[2], argv[1]))
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
