#!/usr/bin/env python3
"""
fix_header.py -- inspect and repair GBA multiboot headers.

Two jobs:

  --check    report what is wrong with a header, needing nothing else
  --donor    repair the logo and checksum, using a ROM you already own

Why a donor is required
-----------------------
Bytes 0x04..0x9F of every GBA header hold Nintendo's logo bitmap. It is their
copyrighted artwork and their trademark, so this tool will not carry a copy and
neither will the firmware. Repair therefore means copying those bytes out of a
dump you own, on your own machine -- the same arrangement as the font patching
flow.

What actually needs fixing
--------------------------
The complement byte at 0xBD is computed from the header's own contents, so it
goes stale the moment anyone edits a title string by hand. That is by far the
most common breakage and needs no donor at all.

A wrong logo is rarer and only turns up in hand-assembled or trimmed images.
Note that the console checks the logo itself, so a bad one fails at the far end
regardless of what any tool on this side thinks -- which is exactly why the
device does not attempt to validate it and this tool exists instead.

Usage
-----
    python3 fix_header.py --check rom.mb
    python3 fix_header.py --check *.mb
    python3 fix_header.py --donor mygame.gba broken.mb
    python3 fix_header.py --donor mygame.gba broken.mb --out fixed.mb
    python3 fix_header.py --donor mygame.gba *.mb --in-place
    python3 fix_header.py --fingerprint mygame.gba > logo_crc.h

The fingerprint
---------------
The console verifies the logo during multiboot, so a wrong one fails *after* a
complete transfer with no diagnostic. The device can warn first if it knows what
a correct logo hashes to -- and a 4-byte CRC32 is a fingerprint, not a copy of
Nintendo's artwork. Generate it from a dump you own; it never ships with the
firmware source.
"""

import argparse
import binascii
import glob
import os
import shutil
import sys

HEADER_LEN = 0xC0
LOGO_START = 0x04
LOGO_END = 0xA0          # exclusive
LOGO_LEN = LOGO_END - LOGO_START   # 156 bytes
TITLE = 0xA0
FIXED_BYTE = 0xB2
CHECK_BYTE = 0xBD

MB_MIN = 0x1A0
MB_MAX = 0x40000


def header_checksum(header: bytes) -> int:
    """0x00 - (0x19 + sum of bytes 0xA0..0xBC), truncated to 8 bits."""
    total = sum(header[TITLE:CHECK_BYTE]) & 0xFF
    return (0 - (total + 0x19)) & 0xFF


def logo_fingerprint(header: bytes) -> int:
    """CRC32 of bytes 0x04..0x9F. Must match rom_logo_fingerprint() in C."""
    return binascii.crc32(header[LOGO_START:LOGO_END]) & 0xFFFFFFFF


def emit_fingerprint(path: str) -> int:
    with open(path, "rb") as fh:
        header = fh.read(HEADER_LEN)
    if len(header) < HEADER_LEN:
        sys.exit(f"{path} is shorter than a header")
    if header[FIXED_BYTE] != 0x96:
        sys.exit(f"{path} has no valid GBA header")
    logo = header[LOGO_START:LOGO_END]
    if logo == bytes(LOGO_LEN):
        sys.exit(f"{path} has a blank logo area")

    crc = logo_fingerprint(header)
    print("/*")
    print(" * logo_crc.h -- GENERATED by tools/fix_header.py --fingerprint")
    print(" *")
    print(" * CRC32 of the 156-byte logo area of a GBA header, taken from a dump")
    print(" * on this machine. It lets the device flag an image whose logo the")
    print(" * console would reject, without carrying the artwork itself.")
    print(" *")
    print(f" * source: {os.path.basename(path)}")
    print(" */")
    print("#pragma once")
    print(f"#define ROM_LOGO_REFERENCE_CRC 0x{crc:08X}u")
    return 0


def describe(data: bytes, donor_logo: bytes | None = None) -> list[str]:
    """Everything wrong with this header, in the order worth fixing."""
    problems = []

    if len(data) < HEADER_LEN:
        return ["file is shorter than a 192-byte header"]
    if len(data) < MB_MIN:
        problems.append(f"too small for multiboot ({len(data)} < {MB_MIN} bytes)")
    if len(data) > MB_MAX:
        problems.append(f"larger than EWRAM ({len(data)} > {MB_MAX} bytes)")

    if data[3] != 0xEA:
        problems.append(f"entry point is not an ARM branch (0x{data[3]:02X}, want 0xEA)")
    if data[FIXED_BYTE] != 0x96:
        problems.append(f"fixed byte 0xB2 is 0x{data[FIXED_BYTE]:02X}, want 0x96")

    want = header_checksum(data)
    if data[CHECK_BYTE] != want:
        problems.append(
            f"complement byte is 0x{data[CHECK_BYTE]:02X}, should be 0x{want:02X}")

    logo = data[LOGO_START:LOGO_END]
    if logo == bytes(LOGO_LEN):
        problems.append("logo area is blank")
    elif donor_logo is not None and logo != donor_logo:
        problems.append("logo does not match the donor")

    return problems


def title_of(data: bytes) -> str:
    raw = data[TITLE:TITLE + 12]
    return raw.decode("ascii", "replace").rstrip("\0 ").strip()


def load_donor(path: str) -> bytes:
    with open(path, "rb") as fh:
        data = fh.read(HEADER_LEN)
    if len(data) < HEADER_LEN:
        sys.exit(f"donor {path} is shorter than a header")

    # A donor whose own header is broken would propagate the breakage.
    if data[FIXED_BYTE] != 0x96:
        sys.exit(f"donor {path} has no valid GBA header (fixed byte is "
                 f"0x{data[FIXED_BYTE]:02X})")
    logo = data[LOGO_START:LOGO_END]
    if logo == bytes(LOGO_LEN):
        sys.exit(f"donor {path} has a blank logo area")
    return logo


def repair(data: bytearray, donor_logo: bytes | None) -> list[str]:
    """Apply fixes in place. Returns what changed."""
    changes = []

    if donor_logo is not None and data[LOGO_START:LOGO_END] != donor_logo:
        data[LOGO_START:LOGO_END] = donor_logo
        changes.append("copied logo from donor")

    if data[FIXED_BYTE] != 0x96:
        data[FIXED_BYTE] = 0x96
        changes.append("set fixed byte 0xB2")

    # Always last: it is computed from the bytes above it.
    want = header_checksum(bytes(data))
    if data[CHECK_BYTE] != want:
        data[CHECK_BYTE] = want
        changes.append(f"recomputed complement byte to 0x{want:02X}")

    return changes


def expand(patterns: list[str]) -> list[str]:
    out = []
    for p in patterns:
        hits = glob.glob(p)
        out.extend(hits if hits else [p])
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("files", nargs="+", help=".mb or .gba files")
    ap.add_argument("--fingerprint", action="store_true",
                    help="emit logo_crc.h from the single input file")
    ap.add_argument("--donor", metavar="ROM",
                    help="a GBA ROM you own, to copy the logo from")
    ap.add_argument("--check", action="store_true",
                    help="report problems without writing anything")
    ap.add_argument("--out", metavar="PATH",
                    help="write here instead of alongside the input "
                         "(single input only)")
    ap.add_argument("--in-place", action="store_true",
                    help="overwrite the inputs, keeping a .bak")
    args = ap.parse_args()

    files = expand(args.files)

    if args.fingerprint:
        if len(files) != 1:
            sys.exit("--fingerprint takes a single ROM")
        return emit_fingerprint(files[0])

    if args.out and len(files) > 1:
        sys.exit("--out takes a single input file")
    if not args.check and not args.donor and not args.in_place:
        # Checksum-only repair needs no donor, but writing still needs a target.
        pass

    donor_logo = load_donor(args.donor) if args.donor else None
    if donor_logo:
        print(f"donor: {args.donor} ({LOGO_LEN}-byte logo)\n")

    failures = 0
    for path in files:
        if not os.path.isfile(path):
            print(f"{path}: not found")
            failures += 1
            continue

        with open(path, "rb") as fh:
            data = bytearray(fh.read())

        problems = describe(bytes(data), donor_logo)
        name = title_of(bytes(data)) if len(data) >= HEADER_LEN else "?"
        label = f"{os.path.basename(path)} [{name}]" if name else os.path.basename(path)

        if not problems:
            print(f"OK    {label}")
            continue

        print(f"FIX   {label}")
        for p in problems:
            print(f"        - {p}")

        if args.check:
            failures += 1
            continue
        if len(data) < HEADER_LEN:
            print("        cannot repair: no header to repair")
            failures += 1
            continue

        changes = repair(data, donor_logo)
        if not changes:
            print("        nothing repairable without a donor "
                  "(rerun with --donor)")
            failures += 1
            continue

        if args.out:
            dest = args.out
        elif args.in_place:
            shutil.copy2(path, path + ".bak")
            dest = path
        else:
            stem, ext = os.path.splitext(path)
            dest = stem + ".fixed" + ext

        with open(dest, "wb") as fh:
            fh.write(data)

        for c in changes:
            print(f"        + {c}")
        print(f"        -> {dest}")

        remaining = describe(bytes(data), donor_logo)
        if remaining:
            print("        still wrong after repair:")
            for r in remaining:
                print(f"        ! {r}")
            failures += 1

    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
